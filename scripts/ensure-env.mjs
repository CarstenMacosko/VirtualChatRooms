// Prepares .env for `pnpm dev`: creates it from .env.example on first run, and fills in values
// that must be generated per machine (the Web Push key pair).
import { generateKeyPairSync } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";

const env = new URL("../.env", import.meta.url);
if (!existsSync(env)) {
  copyFileSync(new URL("../.env.example", import.meta.url), env);
  console.log("Created .env from .env.example");
}

const lines = readFileSync(env, "utf8").split("\n");
const value = (name) =>
  lines
    .find((l) => l.startsWith(`${name}=`))
    ?.slice(name.length + 1)
    .trim();
if (!value("VAPID_PUBLIC_KEY") || !value("VAPID_PRIVATE_KEY")) {
  // Web Push wants a P-256 key pair as base64url: the raw uncompressed public point, and the
  // private scalar.
  const { publicKey, privateKey } = generateKeyPairSync("ec", { namedCurve: "prime256v1" });
  const pub = publicKey.export({ format: "jwk" });
  const priv = privateKey.export({ format: "jwk" });
  const point = Buffer.concat([
    Buffer.from([4]),
    Buffer.from(pub.x, "base64url"),
    Buffer.from(pub.y, "base64url"),
  ]);
  const kept = lines.filter((l) => !/^VAPID_(PUBLIC|PRIVATE)_KEY=/.test(l));
  while (kept.at(-1) === "") kept.pop();
  kept.push(
    "",
    "# Generated by scripts/ensure-env.mjs for Web Push on this machine.",
    `VAPID_PUBLIC_KEY=${point.toString("base64url")}`,
    `VAPID_PRIVATE_KEY=${priv.d}`,
    "",
  );
  writeFileSync(env, kept.join("\n"));
  console.log("Generated Web Push keys in .env");
}
